"""Blast Radius copilot: one question in, one grounded answer out.

    python -m agent.copilot "Who was hit by the EU-2 outage and who wrote to support?"
    python -m agent.copilot                 # interactive
    python -m agent.copilot --tools         # list the tools both MCP servers offer right now

The copilot has no data access of its own. Everything it knows comes from the
tools of the two MCP servers generated by Synapse. Each question opens a fresh
connection to both servers, so a tool added by `synapse build --discover` is
available on the next question.

Exit codes for a single question: 0 answered, 2 no complete answer (round limit,
empty or truncated model output), 3 the model call failed.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from pathlib import Path
from typing import Callable

from .llm import LLMError, make_llm
from .mcp_hub import SEP, McpHub
from .servers import ROOT, load_dotenv, load_servers, scrub, utf8_stdio

SYSTEM_PROMPT = (Path(__file__).parent / "system_prompt.md").read_text(encoding="utf-8")
READ_ONLY_PREFIXES = ("get_", "list_", "find_", "search_")
MAX_TOOL_OUTPUT = 20_000
EXIT_OK, EXIT_INCOMPLETE, EXIT_MODEL_ERROR = 0, 2, 3


def say(text: str = "") -> None:
    """Print with key-like environment values removed. Everything the copilot shows goes through here."""
    print(scrub(str(text)))


def tool_specs(hub: McpHub) -> list[dict]:
    """MCP tool list -> provider-neutral function specs."""
    specs = []
    for tool in hub.tools:
        properties = {}
        for name, spec in (tool.input_schema.get("properties") or {}).items():
            properties[name] = {k: v for k, v in spec.items() if k in ("type", "description", "enum", "items")}
        parameters = {"type": "object", "properties": properties}
        required = [name for name in (tool.input_schema.get("required") or []) if name in properties]
        if required:                      # hosted Synapse servers declare typed, required arguments
            parameters["required"] = required
        specs.append({"name": tool.qualified, "description": f"[{tool.namespace}] {tool.description}", "parameters": parameters})
    return specs


def is_read_only(qualified: str) -> bool:
    return qualified.split(SEP, 1)[-1].startswith(READ_ONLY_PREFIXES)


def find_llm_error(exc: BaseException) -> LLMError | None:
    """Find a model error inside (possibly nested) exception groups raised by the async MCP transport."""
    if isinstance(exc, LLMError):
        return exc
    for inner in getattr(exc, "exceptions", ()) or ():
        found = find_llm_error(inner)
        if found:
            return found
    return None


def _add_usage(total: dict, usage: dict) -> None:
    for key, value in (usage or {}).items():
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            total[key] = total.get(key, 0) + value


async def answer(
    question: str,
    llm,
    mode: str = "local",
    max_rounds: int = 16,
    approve_write: Callable[[str, dict], bool] | None = None,
    on_step: Callable[[dict], None] | None = None,
    extra_instruction: str = "",
) -> dict:
    """Run the tool loop for one question and return the full record of the run.

    A failing model call does not raise: it ends the run with completed=False,
    stop_reason="model_error" and a scrubbed `error`, so the tool calls made so
    far are kept and the MCP sessions are closed normally.
    """
    started = time.time()
    run = {
        "question": question, "mode": mode, "model": getattr(llm, "model", "?"),
        "steps": [], "answer": "", "completed": False, "stop_reason": "", "error": "",
        "llm_usage": [], "usage_total": {},
    }
    async with McpHub(load_servers(mode)) as hub:
        run["tools_available"] = hub.names()
        llm.start(SYSTEM_PROMPT + ("\n\n" + extra_instruction if extra_instruction else ""), question, tool_specs(hub))
        for _ in range(max_rounds):
            try:
                turn = await asyncio.to_thread(llm.next)
            except LLMError as exc:
                run["stop_reason"], run["error"] = "model_error", scrub(str(exc))
                break
            run["llm_usage"].append(turn.usage or {})
            _add_usage(run["usage_total"], turn.usage)
            if turn.incomplete:
                run["answer"] = scrub(turn.text.strip())
                run["stop_reason"] = f"incomplete:{turn.incomplete}"
                break
            if not turn.tool_calls:
                run["answer"] = scrub(turn.text.strip())
                run["completed"] = bool(run["answer"])
                run["stop_reason"] = "answered" if run["completed"] else "empty_answer"
                break
            for call in turn.tool_calls:
                began = time.time()
                if call.error:
                    text, failed = f"Tool call rejected: {call.error}. Send the arguments as a JSON object.", True
                elif not is_read_only(call.name) and not (approve_write and approve_write(call.name, call.arguments)):
                    text, failed = "Tool call blocked: this tool changes data and was not approved by the user.", True
                else:
                    text, failed = await hub.call(call.name, call.arguments)
                text = scrub(text)                      # mask first, cut second
                if len(text) > MAX_TOOL_OUTPUT:
                    text = text[:MAX_TOOL_OUTPUT] + "\n…[truncated]"
                step = {
                    "n": len(run["steps"]) + 1,
                    "system": call.name.split(SEP, 1)[0] if SEP in call.name else "?",
                    "tool": call.name,
                    "arguments": json.loads(scrub(json.dumps(call.arguments, ensure_ascii=False))),
                    "ok": not failed,
                    "ms": int((time.time() - began) * 1000),
                    "chars": len(text),
                    "result_preview": text[:300],
                }
                run["steps"].append(step)
                if on_step:
                    on_step(step)
                llm.add_tool_result(call, text)
        else:
            run["stop_reason"] = "max_rounds"
            run["answer"] = f"Stopped after {max_rounds} tool rounds without a final answer."
    run["systems_used"] = sorted({s["system"] for s in run["steps"] if s["ok"]})
    run["llm_calls"] = getattr(llm, "calls", None)
    run["seconds"] = round(time.time() - started, 1)
    return run


def exit_code(run: dict) -> int:
    if run.get("completed"):
        return EXIT_OK
    return EXIT_MODEL_ERROR if run.get("stop_reason") == "model_error" else EXIT_INCOMPLETE


def print_step(step: dict) -> None:
    args = ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in step["arguments"].items() if v is not None)
    if len(args) > 110:
        args = args[:107] + "..."
    status = "ok" if step["ok"] else "ERROR"
    say(f"  {step['n']:>2}. [{step['system']}] {step['tool'].split(SEP, 1)[-1]}({args}) -> {status}, {step['chars']} chars, {step['ms']} ms")
    if not step["ok"]:
        say(f"      {step['result_preview']}")


async def show_tools(mode: str) -> None:
    async with McpHub(load_servers(mode)) as hub:
        by_system: dict[str, list] = {}
        for tool in hub.tools:
            by_system.setdefault(tool.namespace, []).append(tool)
        for namespace, tools in by_system.items():
            say(f"{namespace}: {len(tools)} tools")
            for tool in tools:
                say(f"  - {tool.name}: {tool.description.splitlines()[0][:110]}")
        say(f"total: {len(hub.tools)} tools")


def ask_approval(name: str, arguments: dict) -> bool:
    if not sys.stdin.isatty():
        return False
    say(f"\n  The copilot wants to run a tool that changes data:\n    {name}({json.dumps(arguments, ensure_ascii=False)})")
    return input("  Allow? [y/N] ").strip().lower() in ("y", "yes")


def run_once(question: str, mode: str, save: bool) -> dict:
    llm = make_llm()
    say(f"\nQ: {question}\n")
    try:
        run = asyncio.run(answer(question, llm, mode=mode, approve_write=ask_approval, on_step=print_step))
    except BaseException as exc:                 # the async transport can wrap errors in exception groups
        wrapped = find_llm_error(exc)
        if wrapped is None:
            raise
        run = {"question": question, "mode": mode, "model": getattr(llm, "model", "?"), "steps": [], "answer": "",
               "completed": False, "stop_reason": "model_error", "error": scrub(str(wrapped)), "systems_used": [],
               "llm_calls": getattr(llm, "calls", None), "seconds": 0.0}
    if run["answer"]:
        say(f"\n{run['answer']}\n")
    if not run["completed"]:
        say(f"\nNo complete answer: {run['stop_reason']}" + (f" ({run['error']})" if run["error"] else ""))
    say(f"[{len(run['steps'])} tool calls across {', '.join(run['systems_used']) or 'no'} systems, {run['llm_calls']} model calls, {run['seconds']} s, model {run['model']}]")
    if save:
        folder = ROOT / "runs"
        folder.mkdir(exist_ok=True)
        target = folder / f"run-{time.strftime('%Y%m%d-%H%M%S')}.json"
        target.write_text(scrub(json.dumps(run, indent=2, ensure_ascii=False)), encoding="utf-8")
        say(f"[saved {target.relative_to(ROOT)}]")
    return run


def main() -> None:
    parser = argparse.ArgumentParser(description="Blast Radius copilot")
    parser.add_argument("question", nargs="*", help="question to answer; omit for interactive mode")
    parser.add_argument("--mode", choices=["local", "hosted"], default="local", help="which Synapse MCP servers to use")
    parser.add_argument("--tools", action="store_true", help="list the tools available right now and exit")
    parser.add_argument("--save", action="store_true", help="save the run (answer and tool trace) under runs/")
    args = parser.parse_args()
    utf8_stdio()
    load_dotenv()

    if args.tools:
        asyncio.run(show_tools(args.mode))
        return
    if args.question:
        sys.exit(exit_code(run_once(" ".join(args.question), args.mode, args.save)))
    say("Blast Radius copilot. Empty line or Ctrl+C to quit, :tools to list tools.")
    while True:
        try:
            question = input("\n> ").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if not question:
            break
        if question == ":tools":
            asyncio.run(show_tools(args.mode))
            continue
        run_once(question, args.mode, args.save)


if __name__ == "__main__":
    main()
