"""Deterministic end-to-end check, no LLM involved.

It walks the same tool chain a good agent would walk, through the two MCP
servers generated by Synapse, and compares the joined result with the values
in eval/ground_truth.py. If this passes, the tools exposed to the agent are
sufficient and the cross-system join is right; the LLM only has to choose the
same calls.

    python -m eval.scripted_check                    # both APIs must be running
    python -m eval.scripted_check --stage baseline   # exactly the 10 base tools must be present
    python -m eval.scripted_check --stage live       # the compensations tool must be present too
    python -m eval.scripted_check --mode hosted

With --stage auto (default) the stage is detected from the tool list, but the
list must still equal one of the two known sets exactly.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys

from agent.mcp_hub import McpHub
from agent.servers import load_dotenv, load_servers, utf8_stdio
from eval import ground_truth

INCIDENT = "INC-2026-11-18-EU2"
QUIET_INCIDENT = "INC-2026-11-12-NA1"       # an incident that affected nobody
COMPENSATIONS_TOOL = "game__list_incident_compensations"
BASE_TOOLS = frozenset({
    "game__list_incidents", "game__get_incident", "game__list_incident_affected_players",
    "game__find_player_by_email", "game__get_player", "game__list_player_purchases",
    "desk__get_ticket", "desk__search_tickets", "desk__list_requester_tickets",
    "desk__list_tickets_awaiting_first_response",
})
LIVE_TOOLS = BASE_TOOLS | {COMPENSATIONS_TOOL}
NOT_CHARGED = "payment_failed_not_charged"


def is_player_not_found(text: str) -> bool:
    """True only for the two confirmed ways `find_player_by_email` reports an unknown address.

    Local server:  "... 404 Client Error: Not Found for url: .../players/by-email/<address>"
    Hosted runner: the API's own JSON body, {"detail": "no player uses the e-mail '<address>'"}
    A network failure, a server error or any other answer is not evidence that the player does not exist.
    """
    if "404 Client Error: Not Found" in text and "/players/by-email/" in text:
        return True
    try:
        body = json.loads(text[text.index("{"):text.rindex("}") + 1])
    except ValueError:
        return False
    detail = body.get("detail") if isinstance(body, dict) else None
    return isinstance(detail, str) and detail.startswith("no player uses the e-mail")


async def q1(hub: McpHub, incident_id: str) -> dict:
    incident = await hub.call_json("game__get_incident", {"incident_id": incident_id})
    affected = await hub.call_json("game__list_incident_affected_players", {"incident_id": incident_id})
    everyone = sorted(row["player_id"] for row in affected["items"])
    empty = {"affected": everyone, "with_tickets": {}, "silent": everyone, "awaiting_first_response": []}
    owner = {email.lower(): row["player_id"] for row in affected["items"] for email in row["emails"]}
    if not owner:
        return empty                     # nobody affected: there is nothing to look up in the support desk
    # Strings only: hosted Synapse tools declare every body field as a required string.
    found = await hub.call_json(
        "desk__search_tickets",
        {"requester_emails": ",".join(sorted(owner)), "created_from": incident["started_at"], "status": ""},
    )
    with_tickets: dict[str, list[str]] = {}
    awaiting: list[str] = []
    for ticket in found["items"]:
        player_id = owner[ticket["requester_email"].lower()]
        with_tickets.setdefault(player_id, []).append(ticket["ticket_id"])
        if ticket["awaiting_first_response"]:
            awaiting.append(ticket["ticket_id"])
    return {
        "affected": everyone,
        "with_tickets": {pid: sorted(ids) for pid, ids in sorted(with_tickets.items())},
        "silent": sorted(set(everyone) - set(with_tickets)),
        "awaiting_first_response": sorted(awaiting),
    }


async def q2(hub: McpHub, ticket_id: str) -> dict:
    ticket = await hub.call_json("desk__get_ticket", {"ticket_id": ticket_id})
    text, is_error = await hub.call("game__find_player_by_email", {"email": ticket["requester_email"]})
    if is_error:
        if is_player_not_found(text):
            return {"player_id": None}   # the game has never heard of this address: no link to a player
        raise RuntimeError(f"game__find_player_by_email failed: {text}")
    player_id = json.loads(text)["player_id"]
    purchases = (await hub.call_json("game__list_player_purchases", {"player_id": player_id}))["items"]
    incidents = await hub.call_json("game__list_incidents", {})
    affected_by = []
    for incident in incidents["items"]:
        rows = await hub.call_json("game__list_incident_affected_players", {"incident_id": incident["incident_id"]})
        if any(row["player_id"] == player_id for row in rows["items"]):
            affected_by.append(incident["incident_id"])
    charges: dict[str, int] = {}
    for purchase in purchases:
        if purchase["status"] != NOT_CHARGED:
            charges[purchase["order_id"]] = charges.get(purchase["order_id"], 0) + 1
    return {
        "player_id": player_id,
        "undelivered_purchase_ids": sorted(p["purchase_id"] for p in purchases if p["status"] == "charged_not_delivered"),
        "affected_by_incidents": sorted(affected_by),
        "double_charged_order_ids": sorted(order for order, count in charges.items() if count > 1),
    }


async def q2_resolution(hub: McpHub, ticket_id: str) -> dict:
    """Needs the compensations tool: was the undelivered purchase settled later?"""
    base = await q2(hub, ticket_id)
    related, settled = [], set()
    for incident_id in base["affected_by_incidents"]:
        ledger = await hub.call_json(COMPENSATIONS_TOOL, {"incident_id": incident_id})
        for row in ledger["items"]:
            if row["related_purchase_id"] in base["undelivered_purchase_ids"]:
                related.append(row["compensation_id"])
                settled.add(row["related_purchase_id"])
    return {
        "player_id": base["player_id"],
        "undelivered_purchase_ids": base["undelivered_purchase_ids"],
        "related_compensation_ids": sorted(related),
        "still_owed_purchase_ids": sorted(set(base["undelivered_purchase_ids"]) - settled),
    }


async def q3(hub: McpHub, incident_id: str) -> dict:
    first = await q1(hub, incident_id)
    ledger = await hub.call_json(COMPENSATIONS_TOOL, {"incident_id": incident_id})
    compensated = {row["player_id"] for row in ledger["items"]} & set(first["affected"])
    return {
        "compensated": sorted(compensated),
        "not_compensated": sorted(set(first["affected"]) - compensated),
        "not_compensated_and_awaiting_reply": sorted(
            pid for pid, ids in first["with_tickets"].items()
            if pid not in compensated and any(t in first["awaiting_first_response"] for t in ids)
        ),
        "not_compensated_and_silent": sorted(set(first["silent"]) - compensated),
    }


async def run(mode: str = "local", stage: str = "auto") -> list[tuple[str, bool, dict, dict]]:
    """Return [(label, passed, got, expected)]."""
    results = []
    async with McpHub(load_servers(mode)) as hub:
        names = set(hub.names())
        if stage == "auto":
            stage = "live" if COMPENSATIONS_TOOL in names else "baseline"
        wanted = LIVE_TOOLS if stage == "live" else BASE_TOOLS
        results.append((
            f"tool list equals the {stage} set ({len(wanted)} tools)",
            names == wanted,
            {"unexpected": sorted(names - wanted), "missing": sorted(wanted - names)},
            {"unexpected": [], "missing": []},
        ))
        cases = [
            (f"Q1 {INCIDENT}: affected players x support tickets", q1(hub, INCIDENT), ground_truth.q1(INCIDENT)),
            (f"Q1 {QUIET_INCIDENT}: incident that affected nobody", q1(hub, QUIET_INCIDENT), ground_truth.q1(QUIET_INCIDENT)),
            ("Q2 T-1042: 'charged, not delivered' claim (true)", q2(hub, "T-1042"), ground_truth.q2("T-1042")),
            ("Q2 T-1047: 'charged twice' claim (false)", q2(hub, "T-1047"), ground_truth.q2("T-1047")),
            ("Q2 T-1051: 'charged twice' claim (true)", q2(hub, "T-1051"), ground_truth.q2("T-1051")),
            ("Q2 T-1045: sender unknown to the game, no player link", q2(hub, "T-1045"), ground_truth.q2("T-1045")),
        ]
        if stage == "live" and COMPENSATIONS_TOOL in names:
            cases.append((f"Q3 {INCIDENT}: compensations x tickets (live endpoint)", q3(hub, INCIDENT), ground_truth.q3(INCIDENT)))
            cases.append(("Q2 T-1042: original charge vs later re-delivery (live endpoint)", q2_resolution(hub, "T-1042"), ground_truth.q2_resolution("T-1042")))
        for label, coroutine, expected in cases:
            try:
                got = await coroutine
            except Exception as exc:                     # a failing chain is a failed case, not a crash
                got = {"error": f"{type(exc).__name__}: {exc}"}
            results.append((label, got == expected, got, expected))
    return results


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mode", choices=["local", "hosted"], default="local")
    parser.add_argument("--stage", choices=["auto", "baseline", "live"], default="auto")
    args = parser.parse_args()
    utf8_stdio()
    load_dotenv()
    failed = False
    for label, passed, got, expected in asyncio.run(run(args.mode, args.stage)):
        print(("PASS  " if passed else "FAIL  ") + label)
        if not passed:
            failed = True
            print("   got     :", got)
            print("   expected:", expected)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
