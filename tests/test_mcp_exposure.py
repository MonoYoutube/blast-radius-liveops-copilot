"""What the agent can reach: the Synapse-generated servers, checked through real MCP sessions."""
import asyncio
import json
import re

import requests

from agent.mcp_hub import McpHub
from agent.servers import ROOT, load_exposure, load_servers
from eval import scripted_check

BASE_TOOLS = scripted_check.BASE_TOOLS
LIVE_TOOL = scripted_check.COMPENSATIONS_TOOL


def test_scripted_check_matches_ground_truth(apis):
    results = asyncio.run(scripted_check.run("local", "baseline"))
    failures = [(label, got, expected) for label, passed, got, expected in results if not passed]
    assert not failures, failures
    assert len(results) == 10                                 # tool list + nine cross-system cases
    labels = " | ".join(label for label, *_ in results)
    assert "by topic" in labels and "incident end vs now" in labels and "settlement unknown without the ledger" in labels


def test_scripted_check_goes_red_when_the_stage_is_wrong(apis):
    """Asking for the live stage while the compensations tool is missing must fail, not adapt."""
    results = asyncio.run(scripted_check.run("local", "live"))
    label, passed, got, _ = results[0]
    assert "live" in label and not passed
    assert got["missing"] == [LIVE_TOOL] and got["unexpected"] == []


def test_tool_list_is_exactly_what_we_chose(apis):
    async def names():
        async with McpHub(load_servers("local")) as hub:
            return set(hub.names())

    assert asyncio.run(names()) == BASE_TOOLS


def test_tool_errors_reach_the_agent_as_errors(apis):
    async def call():
        async with McpHub(load_servers("local")) as hub:
            missing = await hub.call("game__get_incident", {"incident_id": "INC-NOPE"})
            unknown = await hub.call("game__drop_database", {})
            return missing, unknown

    (text, is_error), (text2, is_error2) = asyncio.run(call())
    assert is_error and "404" in text
    assert is_error2 and "Unknown tool" in text2


def test_withheld_endpoints_exist_but_are_not_tools(apis):
    exposure = load_exposure()
    for spec in load_servers("local"):
        paths = requests.get(spec.base_url + "/openapi.json", timeout=10).json()["paths"]
        generated = spec.generated_file.read_text(encoding="utf-8")
        assert "generated by Synapse" in generated
        for row in exposure[spec.key]["withheld"]:
            method, path = row["endpoint"].split(" ", 1)
            assert method.lower() in paths[path], f"{row['endpoint']} should exist in the source system"
        urls = re.findall(r'ENDPOINT_BASE_URL"\]\}([^"]*)"', generated)
        assert "/admin/reseed" not in urls
        assert "requests.delete" not in generated
        assert not any(url.endswith("/replies") for url in urls)


def test_tool_descriptions_fit_synapse_limit(apis):
    """Synapse keeps 500 characters of a docstring on a fresh scan but only 240 once the scan cache is
    reused. Staying at or below 240 makes the generated server identical in both cases."""
    exposure = load_exposure()
    for spec in load_servers("local"):
        paths = requests.get(spec.base_url + "/openapi.json", timeout=10).json()["paths"]
        for row in exposure[spec.key]["expose"]:
            method, path = row["endpoint"].split(" ", 1)
            description = paths[path][method.lower()].get("description", "")
            assert 40 <= len(description) <= 240, f"{row['endpoint']}: description has {len(description)} characters"


def test_exposure_file_is_consistent():
    exposure = json.loads((ROOT / "mcp" / "exposure.json").read_text(encoding="utf-8"))
    for key, cfg in exposure.items():
        listed = [row["endpoint"] for group in ("expose", "withheld", "live_demo") for row in cfg[group]]
        assert len(listed) == len(set(listed)), f"{key}: an endpoint is listed twice"
        assert all(row["why"].strip() for group in ("expose", "withheld", "live_demo") for row in cfg[group])
